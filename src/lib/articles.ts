export const CRITERIA_ARTICLES: Article[] = [
  ...LAYOUTS,
  ...COUNTERTOPS,
  ...HARDWARE,
  ...OPENING,
  ...APPLIANCES,
];

export function getArticle(slug: string): Article | undefined {
  return CRITERIA_ARTICLES.find((a) => a.slug === slug);
}

// Ссылка на статью по критерию+опции. Материалы фасадов ведут на /fasady/[slug],
// остальное — на /stati/[slug]. Возвращает null, если статьи нет.
export function articleHref(criterion: string, optionKey: string): string | null {
  if (criterion === "facade") {
    return MATERIALS.some((m) => m.slug === optionKey) ? `/fasady/${optionKey}` : null;
  }
  const a = CRITERIA_ARTICLES.find((x) => x.criterion === criterion && x.optionKey === optionKey);
  return a ? `/stati/${a.slug}` : null;
}

// Структура для хаба /stati: карточки по категориям (материалы — ссылками на /fasady).
export interface ArticleCard {
  href: string;
  title: string;
  summary: string;
}

export function articlesByCategory(): { category: string; items: ArticleCard[] }[] {
  const groups: { category: string; items: ArticleCard[] }[] = [
    {
      category: "Материалы фасадов",
      items: MATERIALS.map((m) => ({
        href: `/fasady/${m.slug}`,
        title: m.name,
        summary: m.tagline,
      })),
    },
  ];
  const order: ArticleCategory[] = ["Планировка кухни", "Столешницы", "Фурнитура и открывание", "Техника"];
  for (const cat of order) {
    groups.push({
      category: cat,
      items: CRITERIA_ARTICLES.filter((a) => a.category === cat).map((a) => ({
        href: `/stati/${a.slug}`,
        title: a.title,
        summary: a.summary,
      })),
    });
  }
  return groups;
}
